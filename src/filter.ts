// Phase 1: drop noise (lockfiles, generated code, pure renames, formatting) before the LLM sees it.
// Keep NOISE_PATTERNS in sync with the noise list in prompts/review.md.

import type { FileDiff, Hunk } from "./diff.js";

export type NoiseReason = "lockfile" | "generated" | "snapshot" | "rename-only" | "formatting-only";

export interface NoisePattern {
  pattern: RegExp;
  reason: NoiseReason;
}

export const NOISE_PATTERNS: readonly NoisePattern[] = [
  {
    pattern:
      /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb|Cargo\.lock|poetry\.lock|uv\.lock|Gemfile\.lock|go\.sum|composer\.lock)$/,
    reason: "lockfile",
  },
  { pattern: /(^|\/)(dist|build|out|vendor)\//, reason: "generated" },
  { pattern: /\.(min\.js|map)$|\.pb\.go$|_pb2\.py$|\.generated\./, reason: "generated" },
  { pattern: /(^|\/)__snapshots__\/|\.snap$/, reason: "snapshot" },
];

/** Marker comments that code generators put in the first lines of a file. */
const GENERATED_HEADER = /@generated|do not edit|auto-?generated|code generated by|generated by /i;

/** Return the noise reason for a path, or undefined if the path is signal. */
export function classifyPath(path: string): NoiseReason | undefined {
  return NOISE_PATTERNS.find(({ pattern }) => pattern.test(path))?.reason;
}

export interface SkippedFile {
  path: string;
  reason: NoiseReason;
  added: number;
  deleted: number;
}

export interface FilterResult {
  signal: FileDiff[];
  skipped: SkippedFile[];
}

/** Added and deleted line counts for a file. */
export function countChanges(file: FileDiff): { added: number; deleted: number } {
  let added = 0;
  let deleted = 0;
  for (const hunk of file.hunks) {
    for (const line of hunk.lines) {
      if (line.startsWith("+")) added++;
      else if (line.startsWith("-")) deleted++;
    }
  }
  return { added, deleted };
}

/** Why a file is noise, or undefined if a reviewer needs to read it. */
export function noiseReason(file: FileDiff): NoiseReason | undefined {
  const byPath = classifyPath(file.path);
  if (byPath) return byPath;
  if (file.status === "renamed" && file.similarity === 100 && file.hunks.length === 0) return "rename-only";
  if (file.hunks.length > 0 && file.hunks.every(isFormattingOnlyHunk)) return "formatting-only";
  if (file.status === "added" && hasGeneratedHeader(file)) return "generated";
  return undefined;
}

/** Split files into signal and skipped noise. */
export function filterFiles(files: FileDiff[]): FilterResult {
  const result: FilterResult = { signal: [], skipped: [] };
  for (const file of files) {
    const reason = noiseReason(file);
    if (reason) result.skipped.push({ path: file.path, reason, ...countChanges(file) });
    else result.signal.push(file);
  }
  return result;
}

/** True if a hunk only changes whitespace: same code once all whitespace is removed. */
export function isFormattingOnlyHunk(hunk: Hunk): boolean {
  const removed: string[] = [];
  const added: string[] = [];
  for (const line of hunk.lines) {
    if (line.startsWith("-")) removed.push(line.slice(1));
    else if (line.startsWith("+")) added.push(line.slice(1));
  }
  if (removed.length === 0 && added.length === 0) return false;
  const squash = (lines: string[]) => lines.join("").replace(/\s+/g, "");
  return squash(removed) === squash(added);
}

function hasGeneratedHeader(file: FileDiff): boolean {
  const firstLines = file.hunks[0]?.lines.slice(0, 5) ?? [];
  return firstLines.some((line) => GENERATED_HEADER.test(line));
}
