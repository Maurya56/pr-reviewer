import { describe, expect, it } from "vitest";
import type { FileDiff, Hunk } from "../src/diff.js";
import { classifyPath, filterFiles, isFormattingOnlyHunk } from "../src/filter.js";

const hunk = (lines: string[]): Hunk => ({ header: "@@ -1 +1 @@", oldStart: 1, oldLines: 1, newStart: 1, newLines: 1, lines });
const file = (path: string, over: Partial<FileDiff> = {}): FileDiff => ({
  path,
  status: "modified",
  binary: false,
  hunks: [hunk(["-a", "+b"])],
  ...over,
});

describe("classifyPath", () => {
  it.each([
    ["package-lock.json", "lockfile"],
    ["apps/web/pnpm-lock.yaml", "lockfile"],
    ["dist/index.js", "generated"],
    ["src/__snapshots__/view.test.ts.snap", "snapshot"],
  ] as const)("marks %s as %s", (path, reason) => {
    expect(classifyPath(path)).toBe(reason);
  });

  it.each(["src/cli.ts", "src/distribution.ts", "README.md"])("keeps %s as signal", (path) => {
    expect(classifyPath(path)).toBeUndefined();
  });
});

describe("isFormattingOnlyHunk", () => {
  it("is true when only indentation and spacing change", () => {
    expect(isFormattingOnlyHunk(hunk(["-if (x){", "-  y()", "+if (x) {", "+    y()"]))).toBe(true);
  });

  it("is true when lines are only re-wrapped", () => {
    expect(isFormattingOnlyHunk(hunk(["-foo(a, b)", "+foo(", "+  a,", "+  b", "+)"]))).toBe(true);
  });

  it("is false when code changes", () => {
    expect(isFormattingOnlyHunk(hunk(["-foo(a)", "+foo(b)"]))).toBe(false);
  });

  it("is false for a hunk with only context lines", () => {
    expect(isFormattingOnlyHunk(hunk([" a"]))).toBe(false);
  });
});

describe("filterFiles", () => {
  it("skips noise with its reason and line counts, keeps signal", () => {
    const result = filterFiles([
      file("src/app.ts"),
      file("package-lock.json", { hunks: [hunk(["-x", "+y", "+z"])] }),
      file("src/new.ts", { status: "renamed", oldPath: "src/old.ts", similarity: 100, hunks: [] }),
      file("src/fmt.ts", { hunks: [hunk(["-a  =  1", "+a = 1"])] }),
      file("src/api_pb.ts", { status: "added", hunks: [hunk(["+// Code generated by protoc. DO NOT EDIT.", "+x"])] }),
    ]);
    expect(result.signal.map((f) => f.path)).toEqual(["src/app.ts"]);
    expect(result.skipped).toEqual([
      { path: "package-lock.json", reason: "lockfile", added: 2, deleted: 1 },
      { path: "src/new.ts", reason: "rename-only", added: 0, deleted: 0 },
      { path: "src/fmt.ts", reason: "formatting-only", added: 1, deleted: 1 },
      { path: "src/api_pb.ts", reason: "generated", added: 2, deleted: 0 },
    ]);
  });

  it("keeps a renamed file that was also edited", () => {
    const renamed = file("src/new.ts", { status: "renamed", oldPath: "src/old.ts", similarity: 90 });
    expect(filterFiles([renamed]).signal).toHaveLength(1);
  });

  it("doesn't treat a comment that merely mentions generating as a generated header", () => {
    const f = file("scripts/build.mjs", { status: "added", hunks: [hunk(["+// Generate the skill file.", "+x"])] });
    expect(filterFiles([f]).signal).toHaveLength(1);
  });
});
